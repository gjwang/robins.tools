/**
 * Serialize a JSON-LD object for injection via dangerouslySetInnerHTML. The `<`
 * escape prevents a `</script>` sequence in any string field from closing the
 * tag early, which is the one XSS vector for inline JSON-LD.
 */
function serialize(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}

const websiteNode = {
  "@type": "WebSite",
  "@id": `${SITE_URL}/#website`,
  name: SITE_NAME,
  url: SITE_URL,
  description: SITE_DESCRIPTION,
  inLanguage: "en",
  sameAs: [X_URL, TELEGRAM_URL],
};

/** WebSite + SoftwareApplication graph for the landing page. */
export function landingJsonLd(): string {
  return serialize({
    "@context": "https://schema.org",
    "@graph": [
      websiteNode,
      {
        "@type": "SoftwareApplication",
        "@id": `${SITE_URL}/#app`,
        name: SITE_NAME,
        url: SITE_URL,
        description: SITE_DESCRIPTION,
        applicationCategory: "DeveloperApplication",
        operatingSystem: "Web",
        isAccessibleForFree: true,
        offers: {
          "@type": "Offer",
          price: "0",
          priceCurrency: "USD",
        },
        license: MIT_LICENSE_URL,
        isPartOf: { "@id": `${SITE_URL}/#website` },
      },
    ],
  });
}

/** SoftwareApplication + BreadcrumbList graph for a single tool page. */
export function toolJsonLd(slug: string): string {
  const tool = getTool(slug);
  if (!tool) return serialize({ "@context": "https://schema.org" });

  const url = `${SITE_URL}/tools/${slug}`;

  return serialize({
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "SoftwareApplication",
        name: tool.name,
        url,
        description: tool.description,
        applicationCategory: "DeveloperApplication",
        operatingSystem: "Web",
        isAccessibleForFree: true,
        offers: {
          "@type": "Offer",
          price: "0",
          priceCurrency: "USD",
        },
        license: MIT_LICENSE_URL,
        isPartOf: { "@id": `${SITE_URL}/#website` },
      },
      breadcrumbNode([
        { name: "Home", url: SITE_URL },
        { name: "Tools", url: `${SITE_URL}/tools` },
        { name: tool.name, url },
      ]),
    ],
  });
}

/** TechArticle + BreadcrumbList graph for a docs page. */
export function docJsonLd(opts: {
  title: string;
  description: string;
  /** Docs path, e.g. "/docs/tools/merkle". */
  path: string;
}): string {
  const url = `${SITE_URL}${opts.path}`;

  return serialize({
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "TechArticle",
        headline: opts.title,
        description: opts.description,
        url,
        inLanguage: "en",
        isPartOf: { "@id": `${SITE_URL}/#website` },
      },
      breadcrumbNode([
        { name: "Home", url: SITE_URL },
        { name: "Docs", url: `${SITE_URL}/docs` },
        { name: opts.title, url },
      ]),
    ],
  });
}

function breadcrumbNode(items: { name: string; url: string }[]) {
  return {
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: item.url,
    })),
  };
}
