import type { Metadata } from "next";
import { TELEGRAM_URL, X_URL } from "@/lib/site";

import { getTool } from "@/lib/tools";

/** Canonical origin for the deployed site. No trailing slash. */
export const SITE_URL = "https://robins.tools";
export const SITE_NAME = "robins.tools";

/** Default document title for the home route (og/twitter mirror this). */
export const SITE_TITLE_DEFAULT =
  "robins.tools · the open-source toolkit for Robinhood Chain";

/**
 * Root-level site description. Leads with the category claim and is shared by
 * the root metadata (layout) and the landing-page JSON-LD, so the claim lives
 * in exactly one place.
 */
export const SITE_DESCRIPTION =
  "The first open-source toolkit for Robinhood Chain: batch transfers, token deployment, approval auditing and more, running entirely in your browser.";

/** Shared Open Graph / Twitter card image (1200x630, generated by scripts/generate-og.mjs). */
const OG_IMAGE = {
  url: "/og.png",
  width: 1200,
  height: 630,
  alt: "robins.tools: open-source tools for Robinhood Chain",
} as const;

const MIT_LICENSE_URL = "https://opensource.org/licenses/MIT";

interface PageMetaOptions {
  /** Title segment. Rendered through the "%s · robins.tools" template unless `absoluteTitle` is set. */
  title: string;
  description: string;
  /** Canonical path, e.g. "/tools" or "/tools/multisender". Resolved against metadataBase. */
  path: string;
  /** Full Open Graph / Twitter title. Defaults to `${title} · robins.tools`. */
  ogTitle?: string;
  /** When true, `title` is used verbatim with no template applied. */
  absoluteTitle?: boolean;
  /** Open Graph object type. Defaults to "website". */
  ogType?: "website" | "article";
}

/**
 * Build a complete Metadata object for a page: canonical URL plus Open Graph and
 * Twitter cards. Next does not copy a page's title/description into og/twitter, so
 * every field is set explicitly here.
 */
export function pageMetadata({
  title,
  description,
  path,
  ogTitle,
  absoluteTitle = false,
  ogType = "website",
}: PageMetaOptions): Metadata {
  const resolvedOgTitle = ogTitle ?? `${title} · ${SITE_NAME}`;

  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: ogType,
      url: path,
      siteName: SITE_NAME,
      title: resolvedOgTitle,
      description,
      images: [OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: resolvedOgTitle,
      description,
      images: [OG_IMAGE.url],
    },
  };
}

/**
 * Page metadata for a tool, derived from the tool registry so titles and
 * descriptions stay in one place instead of thirteen hand-rolled blocks.
 */
export function toolPageMetadata(slug: string): Metadata {
  const tool = getTool(slug);
  if (!tool) return {};

  return pageMetadata({
    title: tool.name,
    description: tool.description,
    path: `/tools/${slug}`,
    ogTitle: `${tool.name} · ${SITE_NAME}`,
  });
}

